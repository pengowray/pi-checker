# Compute zeta(5) and write docs/long/zeta5.js. OEIS A013663 only lists ~100
# digits, so the digits are computed here two independent ways and must agree:
#   1. mpmath's zeta(5)
#   2. Plouffe's formula
#        zeta(5) = pi^5/294 - (72/35) S(-1) - (2/35) S(+1),
#        S(c) = sum over n >= 1 of 1 / (n^5 (e^(2 pi n) + c))
#
# Needs mpmath (gmpy2 makes it much faster). Run from the repo root:
#   python3 scripts/zeta5.py            # 20001 digits, a few seconds
import os
import sys
from mpmath import mp, mpf, zeta, pi, exp, nstr

DIGITS = int(sys.argv[1]) if len(sys.argv) > 1 else 20001
GUARD = 20
mp.dps = DIGITS + GUARD + 10

a = zeta(5)

q = exp(-2 * pi)
qn, sm, sp, n = mpf(1), mpf(0), mpf(0), 0
eps = mpf(10) ** -(DIGITS + GUARD + 5)
while True:
    n += 1
    qn *= q
    n5 = mpf(n) ** 5
    tm = qn / (1 - qn) / n5   # 1 / (n^5 (e^(2 pi n) - 1))
    sm += tm
    sp += qn / (1 + qn) / n5  # 1 / (n^5 (e^(2 pi n) + 1))
    if tm < eps:
        break
b = pi ** 5 / 294 - mpf(72) / 35 * sm - mpf(2) / 35 * sp

sa = nstr(a, DIGITS + GUARD, strip_zeros=False)
sb = nstr(b, DIGITS + GUARD, strip_zeros=False)
assert sa == sb, 'mpmath and Plouffe disagree'
assert sa.startswith('1.')
digits = sa[2:2 + DIGITS]

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'docs', 'long', 'zeta5.js')
banner = (
    '// Long decimal expansion of ζ(5), post-decimal-point.\n'
    f'// Computed by scripts/zeta5.py ({len(digits)} digits; mpmath and Plouffe\'s formula agree).\n'
    '// Generated by scripts/zeta5.py — do not edit by hand.\n'
)
with open(out, 'w', newline='\n') as f:
    f.write(banner + f'(window.LONG_DIGITS = window.LONG_DIGITS || {{}})["zeta5"] = "{digits}";\n')
print(f'zeta5: {len(digits)} digits -> docs/long/zeta5.js ({n} Plouffe terms)')
